#!/usr/bin/env python3
"""Synthetic, private-data-free tests for deterministic, correction-preserving export."""
import copy
import json
from pathlib import Path
import tempfile
import unittest

from export_ai_drafts import build_export
from validate_translations import CATALOGS, PLURALS, sha


def unit(value):
    return {'stringUnit':{'state':'translated','value':value}}


class ExportTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.repo=Path(self.tmp.name)/'public'
        self.private=Path(self.tmp.name)/'private'
        (self.repo/'docs').mkdir(parents=True)
        self.private.mkdir()
        self.base={'format':1,'locales':list(PLURALS),'catalogs':{}}
        self.old_key='tendoTodayToday'
        self.new_key='tendoFocusStartFocus'
        for name in CATALOGS:
            en=unit('Reference')
            public_source={'comment':'Safe public context.','extractionState':'manual','english':en}
            info={'keys':[self.old_key], 'public_source':{self.old_key:sha(public_source)},
                  'english':{self.old_key:sha(en)},'initial_targets':{}}
            priv_strings={}
            new_entry={'comment':'Private path Tendo/Features/Focus/Secret.swift:78',
                       'extractionState':'manual','localizations':{'en':unit('Another reference')}}
            original={'comment':'Secret/private source.swift:14','extractionState':'manual',
                      'localizations':{'en':unit('Reference')}}
            for lang in PLURALS:
                target=unit('AI value '+lang)
                original['localizations'][lang]=copy.deepcopy(target)
                new_entry['localizations'][lang]=unit('Draft '+lang)
                info['initial_targets'][lang]={self.old_key:sha(target)}
                public_entry={'comment':'Safe public context.','extractionState':'manual',
                              'localizations':{'en':copy.deepcopy(en),lang:copy.deepcopy(target)}}
                out={'sourceLanguage':'en','version':'1.1','strings':{self.old_key:public_entry}}
                path=self.repo/'locales'/lang
                path.mkdir(parents=True,exist_ok=True)
                (path/name).write_text(json.dumps(out),encoding='utf-8')
            priv_strings[self.old_key]=original
            priv_strings[self.new_key]=new_entry
            if name == 'Localizable.xcstrings':
                priv_strings['%@']={'isCommentAutoGenerated':True,'comment':'Technical formatting placeholder',
                                   'localizations':{'en':unit('%@'),**{lang:unit('%@') for lang in PLURALS}}}
            (self.private/name).write_text(json.dumps({'sourceLanguage':'en','version':'1.1','strings':priv_strings}),encoding='utf-8')
            self.base['catalogs'][name]=info
        (self.repo/'docs/export-baseline.json').write_text(json.dumps(self.base),encoding='utf-8')

    def mutate_catalog(self,path,callback):
        data=json.loads(path.read_text(encoding='utf-8'))
        callback(data)
        path.write_text(json.dumps(data),encoding='utf-8')

    def test_adds_complete_drafts_with_sanitized_comments(self):
        output,summary=build_export(self.repo,self.private)
        self.assertEqual(summary['counts']['Localizable.xcstrings'],2)
        sl=json.loads(output[Path('locales/sl/Localizable.xcstrings')])
        new=sl['strings'][self.new_key]
        self.assertNotIn('swift',new['comment'].lower())
        self.assertEqual(new['localizations']['sl']['stringUnit']['value'],'Draft sl')
        self.assertEqual(new['localizations']['en']['stringUnit']['value'],'Another reference')
        self.assertEqual(summary['preserved_differences'],0)

    def test_preserves_edited_public_translation(self):
        path=self.repo/'locales/sl/Localizable.xcstrings'
        self.mutate_catalog(path,lambda d:d['strings'][self.old_key]['localizations']['sl']['stringUnit'].update(value='Human-corrected'))
        output,summary=build_export(self.repo,self.private)
        pack=json.loads(output[Path('locales/sl/Localizable.xcstrings')])
        self.assertEqual(pack['strings'][self.old_key]['localizations']['sl']['stringUnit']['value'],'Human-corrected')
        base=json.loads(output[Path('docs/export-baseline.json')])
        self.assertEqual(base['catalogs']['Localizable.xcstrings']['initial_targets']['sl'][self.old_key],sha(unit('AI value sl')))
        self.assertEqual(summary['preserved_differences'],1)

    def test_blocks_changed_source_for_previously_published_key(self):
        path=self.private/'Localizable.xcstrings'
        self.mutate_catalog(path,lambda d:d['strings'][self.old_key]['localizations']['en']['stringUnit'].update(value='Changed source'))
        with self.assertRaisesRegex(ValueError,'English source changed'):
            build_export(self.repo,self.private)

    def test_blocks_private_path_in_a_translatable_value(self):
        path=self.private/'Localizable.xcstrings'
        self.mutate_catalog(path,lambda d:d['strings'][self.new_key]['localizations']['sl']['stringUnit'].update(value='/Users/local/private'))
        with self.assertRaisesRegex(ValueError,'Potentially sensitive'):
            build_export(self.repo,self.private)


if __name__=='__main__':
    unittest.main()
